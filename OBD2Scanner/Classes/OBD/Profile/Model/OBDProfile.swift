import Foundation

/// Декларативное описание того, как читать данные из конкретного семейства ECU.
///
/// Профиль — это данные (JSON), а не код. Один универсальный движок умеет
/// исполнить любой профиль: открыть сессию с нужным блоком, опросить параметры,
/// прочитать DTC и freeze frame. Стандартный OBD-II (SAE J1979) описывается
/// этим же типом — он всегда включён как база, производительские профили
/// добавляют данные поверх.
///
/// Формат подробно описан в `Docs/OBD2_PROFILE_FORMAT.md`.
struct OBDProfile: Codable, Equatable {
    /// Версия схемы. Движок отказывается исполнять незнакомую версию —
    /// это важно, когда профили начнут приходить с сервера.
    let schemaVersion: Int
    /// Уникальный идентификатор профиля, напр. `"obd2-standard"`, `"toyota-tnga"`.
    let id: String
    /// Человекочитаемое имя для UI/логов.
    let name: String
    /// Если авто подходит под несколько профилей — берётся больший приоритет.
    /// У стандартного профиля приоритет 0, у производительских — выше.
    let priority: Int
    /// Критерии подбора профиля под конкретный автомобиль.
    let match: ProfileMatch
    /// Параметры шины (номер протокола ELM327).
    let bus: BusConfig
    /// Блоки управления, которые описывает профиль (двигатель, коробка, ABS…).
    let ecus: [ECUDefinition]

    /// Текущая версия схемы, которую понимает движок.
    static let currentSchemaVersion = 1
}

/// Правила подбора профиля. Все указанные поля работают как логическое «И»;
/// пропущенное поле означает «подходит любой».
struct ProfileMatch: Codable, Equatable {
    /// Марки в нижнем регистре, напр. `["toyota", "lexus"]`.
    let brands: [String]?
    /// Модели в нижнем регистре, напр. `["camry", "rav4"]` — для профилей,
    /// привязанных к платформе, а не ко всей марке.
    let models: [String]?
    /// Типы топлива, напр. `["petrol", "hybrid"]`.
    /// ВНИМАНИЕ: в приложении пока нет источника типа топлива (в `Vehicle`
    /// поля нет) — профиль с этим критерием не подберётся никогда.
    /// Не использовать, пока не подключим определение топлива (VIN/PID 0151).
    let fuelTypes: [String]?
    /// Диапазон годов выпуска.
    let years: YearRange?
    /// Допустимые World Manufacturer Identifier — первые 3 символа VIN.
    let vinWMI: [String]?

    struct YearRange: Codable, Equatable {
        let from: Int?
        let to: Int?
    }
}

/// Параметры шины для работы через ELM327.
struct BusConfig: Codable, Equatable {
    /// Номер протокола ELM327 для команды `ATSP`.
    /// `"6"` = CAN 11 бит 500 кбит (почти все машины с ~2008 г.),
    /// `"0"` = автоопределение (используется стандартным профилем).
    let elmProtocol: String
}
